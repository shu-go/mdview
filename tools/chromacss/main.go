// Command chromacss generates frontend/src/styles/highlight.css: the chroma
// syntax highlighting classes for the light and dark themes.
//
//	go run ./tools/chromacss > frontend/src/styles/highlight.css
package main

import (
	"bytes"
	"fmt"
	"os"
	"regexp"
	"strings"

	chromahtml "github.com/alecthomas/chroma/v2/formatters/html"
	"github.com/alecthomas/chroma/v2/styles"
)

var ruleRe = regexp.MustCompile(`(?m)^(/\*[^*]*\*/ )?(\S[^{]*)\{([^}]*)\}`)

func main() {
	f := chromahtml.New(chromahtml.WithClasses(true))
	var out strings.Builder
	out.WriteString("/* Syntax highlighting (generated by tools/chromacss; do not edit by hand). */\n")
	for _, t := range []struct{ theme, style string }{{"light", "github"}, {"dark", "github-dark"}} {
		var buf bytes.Buffer
		if err := f.WriteCSS(&buf, styles.Get(t.style)); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		fmt.Fprintf(&out, "\n/* %s: %s */\n", t.theme, t.style)
		for _, m := range ruleRe.FindAllStringSubmatch(buf.String(), -1) {
			sel := strings.TrimSpace(m[2])
			body := strings.TrimSpace(m[3])
			if !strings.HasPrefix(sel, ".chroma") {
				continue // .bg etc.
			}
			// The code block background comes from the app's CSS variables.
			if sel == ".chroma" {
				continue
			}
			fmt.Fprintf(&out, "[data-theme=\"%s\"] %s { %s }\n", t.theme, sel, body)
		}
	}
	fmt.Print(out.String())
}
